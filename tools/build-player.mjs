#!/usr/bin/env node
// core/ and web/host.js as one page, for a game whose web view is handed HTML, not a server
// (the Unity package): unity/Runtime/Resources/IndieAdsPlayer.html, which is committed, so a
// game that takes the package needs no Node. Run after any change to core/ or web/:
//
//   node tools/build-player.mjs          (wants esbuild: `npx` fetches it, or ESBUILD=<path to its binary>)
//
// `--check` builds and compares instead of writing: 1 if the committed page is stale.
import * as icons from '../core/controlIcons.js';
import { CONTROL_THEME } from '../core/controlTheme.js';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url), out = new URL('unity/Runtime/Resources/IndieAdsPlayer.html', root);
// One source font feeds the offline web bundle and Unity Resources.
const fontModule = new URL('core/controlFont.js', root);
const fontData = readFileSync(new URL('unity/Runtime/Resources/IndieAds/Cairo-Black.ttf', root)).toString('base64');
const fontSource = `// Generated by tools/build-player.mjs. Cairo Black: see unity/Runtime/Resources/IndieAds/Cairo-OFL.txt.\nexport const CONTROL_FONT = 'data:font/ttf;base64,${fontData}';\n`;
if (process.argv.includes('--check')) {
  let now = ''; try { now = readFileSync(fontModule, 'utf8'); } catch {}
  if (now !== fontSource) { console.error('core/controlFont.js is stale: run tools/build-player.mjs'); process.exit(1); }
} else writeFileSync(fontModule, fontSource);
// es2020: every web view a game of ours still runs on (iOS 14's WKWebView, Android's System WebView 80+)
const args = [fileURLToPath(new URL('web/host.js', root)), '--bundle', '--format=iife', '--minify', '--target=es2020', '--charset=utf8', '--log-level=warning'];
const [cmd, ...pre] = process.env.ESBUILD ? [process.env.ESBUILD] : ['npx', '--yes', 'esbuild@0.25'];
const js = execFileSync(cmd, [...pre, ...args], { encoding: 'utf8', maxBuffer: 16e6 }).trim();
if (/<\/script/i.test(js)) throw new Error('the bundle would end its own <script>');

// transparent until the player draws: the game shows through a web view with nothing in it
const html = `<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<style>html, body { margin: 0; height: 100%; background: transparent; overflow: hidden; }</style>
</head><body><script>
${js}
</script></body></html>
`;
// Generate Unity's data from the exact artwork and theme bundled into the web player.
// Renderer adapters consume this file; never maintain a second set of icon literals.
const assetOut = new URL('unity/Runtime/EditorAdAssets.cs', root);
const fields = Object.entries(CONTROL_THEME).map(([key, value]) =>
  `        internal const float ${key[0].toUpperCase() + key.slice(1)} = ${value}f;`);
const names = { SKIP_ICON: 'Skip', CLOSE_ICON: 'Close', AD_LABEL_BG: 'Tag', INFO_BG: 'Info' };
for (const [key, name] of Object.entries(names)) {
  fields.push(`        internal const string ${name} = "${icons[key].split(',')[1]}";`);
}
const assets = `// Generated by tools/build-player.mjs from core/controlIcons.js and controlTheme.js.
#if UNITY_EDITOR && INDIEADS_HAS_VIDEO && INDIEADS_HAS_IMGUI && INDIEADS_HAS_WEBREQUEST
namespace IndieAdNetwork
{
    internal static class EditorAdAssets
    {
${fields.join('\n')}
    }
}
#endif
`;
for (const [file, content] of [[out, html], [assetOut, assets]]) {
  if (process.argv.includes('--check')) {
    let now = ''; try { now = readFileSync(file, 'utf8'); } catch { /* not built yet */ }
    if (now !== content) { console.error(`${fileURLToPath(file)} is stale: run tools/build-player.mjs`); process.exitCode = 1; }
  } else {
    writeFileSync(file, content);
    console.log(`${fileURLToPath(file)}  ${(content.length / 1024).toFixed(1)} KB`);
  }
}
